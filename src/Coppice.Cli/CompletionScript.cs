using System.Text;

namespace Coppice.Cli;

/// <summary>
/// Generates self-contained completion scripts for PowerShell, bash, zsh and fish (T-042,
/// nice-to-have #5).
/// <para>
/// The command list is taken from <see cref="CoppiceApp.Verbs"/> rather than hard-coded here, so a new
/// verb is completable the moment it is dispatchable. The common flags are the ones the CLI documents;
/// each script is written in its shell's own idiom and installed from a single file, with no helper
/// package, no network lookup and nothing sourced at completion time.
/// </para>
/// </summary>
public static class CompletionScript
{
    /// <summary>The shells this build can emit, in a stable order.</summary>
    public static IReadOnlyList<string> Shells { get; } = ["bash", "fish", "powershell", "zsh"];

    /// <summary>
    /// The documented common flags every command shares. Kept in one place so the four scripts cannot
    /// drift from each other or from the help text.
    /// </summary>
    public static IReadOnlyList<string> Flags { get; } =
    [
        "--json",
        "--ci",
        "--no-color",
        "--projects",
        "--policy",
        "--keep-latest",
        "--out",
        "--plan",
        "--yes",
        "--strict",
        "--resume",
    ];

    /// <summary>Flags that take a value; the shell should not offer another flag in that position.</summary>
    private static readonly string[] ValueFlags = ["--projects", "--policy", "--keep-latest", "--out", "--plan"];

    public static bool IsSupported(string? shell) =>
        shell is not null && Shells.Contains(shell, StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Renders the completion script for <paramref name="shell"/>. Verbs are de-duplicated and
    /// ordinal-sorted so the same build always emits the same bytes.
    /// </summary>
    public static string Render(string shell, IEnumerable<string> verbs)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(shell);
        ArgumentNullException.ThrowIfNull(verbs);

        if (!IsSupported(shell))
        {
            throw new ArgumentException(
                $"unknown shell '{shell}'; expected powershell, bash, zsh or fish",
                nameof(shell));
        }

        string[] ordered = [.. verbs.Where(v => !string.IsNullOrWhiteSpace(v)).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];

        if (ordered.Length == 0)
        {
            throw new ArgumentException("a completion script needs at least one verb", nameof(verbs));
        }

        return shell.ToLowerInvariant() switch
        {
            "powershell" => PowerShell(ordered),
            "bash" => Bash(ordered),
            "zsh" => Zsh(ordered),
            "fish" => Fish(ordered),
            _ => throw new ArgumentException($"unknown shell '{shell}'", nameof(shell)),
        };
    }

    private static string PowerShell(string[] verbs)
    {
        var script = new StringBuilder();

        script.Append("# coppice completions for PowerShell.\n");
        script.Append("# Generated by 'coppice completions powershell'.\n");
        script.Append("# Load for this session: . (coppice completions powershell | Out-String)\n");
        script.Append("# Keep it: append the output to your $PROFILE.\n");
        script.Append("Register-ArgumentCompleter -Native -CommandName coppice -ScriptBlock {\n");
        script.Append("    param($wordToComplete, $commandAst, $cursorPosition)\n\n");
        script.Append("    $verbs = @(").Append(QuoteAll(verbs, '\'')).Append(")\n");
        script.Append("    $flags = @(").Append(QuoteAll(Flags, '\'')).Append(")\n\n");
        script.Append("    $candidates = if ($commandAst.CommandElements.Count -le 2) {\n");
        script.Append("        $verbs + $flags\n");
        script.Append("    }\n");
        script.Append("    else {\n");
        script.Append("        $flags\n");
        script.Append("    }\n\n");
        script.Append("    $candidates |\n");
        script.Append("        Where-Object { $_ -like \"$wordToComplete*\" } |\n");
        script.Append("        ForEach-Object {\n");
        script.Append("            [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)\n");
        script.Append("        }\n");
        script.Append("}\n");

        return script.ToString();
    }

    private static string Bash(string[] verbs)
    {
        var script = new StringBuilder();

        script.Append("# coppice completions for bash.\n");
        script.Append("# Generated by 'coppice completions bash'.\n");
        script.Append("# Install: coppice completions bash > ~/.local/share/bash-completion/completions/coppice\n");
        script.Append("_coppice_completions()\n");
        script.Append("{\n");
        script.Append("    local cur prev\n");
        script.Append("    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n");
        script.Append("    prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n\n");
        script.Append("    local verbs=\"").Append(string.Join(' ', verbs)).Append("\"\n");
        script.Append("    local flags=\"").Append(string.Join(' ', Flags)).Append("\"\n\n");
        script.Append("    case \"$prev\" in\n");
        script.Append("        ").Append(string.Join('|', ValueFlags)).Append(")\n");
        script.Append("            COMPREPLY=()\n");
        script.Append("            return 0\n");
        script.Append("            ;;\n");
        script.Append("    esac\n\n");
        script.Append("    if [ \"$COMP_CWORD\" -eq 1 ]; then\n");
        script.Append("        COMPREPLY=( $(compgen -W \"$verbs $flags\" -- \"$cur\") )\n");
        script.Append("    else\n");
        script.Append("        COMPREPLY=( $(compgen -W \"$flags\" -- \"$cur\") )\n");
        script.Append("    fi\n");
        script.Append("}\n\n");
        script.Append("complete -F _coppice_completions coppice\n");

        return script.ToString();
    }

    private static string Zsh(string[] verbs)
    {
        var script = new StringBuilder();

        // #compdef must be the first line for the file to autoload as a completion function.
        script.Append("#compdef coppice\n");
        script.Append("# coppice completions for zsh.\n");
        script.Append("# Generated by 'coppice completions zsh'.\n");
        script.Append("# Install: coppice completions zsh > \"${fpath[1]}/_coppice\"\n\n");
        script.Append("_coppice()\n");
        script.Append("{\n");
        script.Append("    local -a verbs flags\n");
        script.Append("    verbs=(").Append(string.Join(' ', verbs)).Append(")\n");
        script.Append("    flags=(").Append(string.Join(' ', Flags)).Append(")\n\n");
        script.Append("    if (( CURRENT == 2 )); then\n");
        script.Append("        _describe -t commands 'coppice command' verbs\n");
        script.Append("    else\n");
        script.Append("        _describe -t options 'coppice option' flags\n");
        script.Append("    fi\n");
        script.Append("}\n\n");
        script.Append("compdef _coppice coppice\n");

        return script.ToString();
    }

    private static string Fish(string[] verbs)
    {
        var script = new StringBuilder();

        script.Append("# coppice completions for fish.\n");
        script.Append("# Generated by 'coppice completions fish'.\n");
        script.Append("# Install: coppice completions fish > ~/.config/fish/completions/coppice.fish\n\n");
        script.Append("complete -c coppice -f\n\n");

        foreach (string verb in verbs)
        {
            script.Append("complete -c coppice -n '__fish_use_subcommand' -a '")
                .Append(verb)
                .Append("' -d '")
                .Append(FishDescription(verb))
                .Append("'\n");
        }

        script.Append('\n');

        foreach (string flag in Flags)
        {
            string name = flag[2..];

            script.Append("complete -c coppice -l ").Append(name);

            if (ValueFlags.Contains(flag, StringComparer.Ordinal))
            {
                script.Append(" -r");
            }

            script.Append(" -d '").Append(FishDescription(flag)).Append("'\n");
        }

        return script.ToString();
    }

    /// <summary>
    /// A short description for a known verb or flag; a generic one for anything a later card adds.
    /// These are static literals and deliberately contain no quote characters, so they cannot terminate
    /// the fish string they live in.
    /// </summary>
    private static string FishDescription(string name) => name switch
    {
        "apply" => "execute a plan",
        "audit" => "show or verify the mutation log",
        "completions" => "print a shell completion script",
        "doctor" => "resolve locations and report what was found",
        "plan" => "build a plan from the latest snapshot",
        "quarantine" => "inspect, restore or discard quarantined items",
        "roots" => "show locations and how they resolved",
        "scan" => "inventory caches and store a snapshot",
        "tui" => "open the keyboard-driven screens",
        "--json" => "machine-readable output",
        "--ci" => "non-interactive machine-readable mode",
        "--no-color" => "never emit color",
        "--projects" => "project root to scan (repeatable)",
        "--policy" => "policy preset",
        "--keep-latest" => "keep the newest N versions",
        "--out" => "write output to a file",
        "--plan" => "path to a plan file",
        "--yes" => "answer yes to every confirmation",
        "--strict" => "fail on any step error",
        "--resume" => "resume an interrupted apply",
        _ => "coppice option",
    };

    private static string QuoteAll(IReadOnlyList<string> values, char quote) =>
        string.Join(", ", values.Select(v => $"{quote}{v}{quote}"));
}
